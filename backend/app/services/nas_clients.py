"""Renders FreeRADIUS client definitions from nas_devices into the shared
clients file (settings.radius_clients_path). The freeradius container
watches that file's checksum and restarts radiusd when it changes
(radius/entrypoint.sh) — FreeRADIUS 3 doesn't reload clients on HUP.

Adding a NAS is therefore an API call, not a config edit: the NAS list in
Atlas *is* the set of routers allowed to authenticate against the engine.
"""

import hashlib
import os
import re
import tempfile
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import settings
from app.models.nas import NasDevice
from app.security.secrets import decrypt_secret

HEADER = (
    "# GENERATED by the engine from nas_devices — do not edit by hand.\n"
    "# Change NAS entries through the admin API (Atlas > FreeRADIUS > NAS).\n\n"
)


def _ident(name: str) -> str:
    return "nas_" + re.sub(r"[^A-Za-z0-9_]", "_", name)[:48]


def render(devices: list[tuple[str, str, str]]) -> str:
    """devices: (name, ip, plaintext secret). Secrets are validated at the API
    to exclude quote and backslash, so no escaping games here."""
    blocks = [HEADER]
    seen: set[str] = set()
    for name, ip, secret in sorted(devices, key=lambda d: d[1]):
        ident = _ident(name)
        while ident in seen:
            ident += "_"
        seen.add(ident)
        blocks.append(
            f"client {ident} {{\n"
            f"\tipaddr = {ip}\n"
            f"\tsecret = \"{secret}\"\n"
            f"\tshortname = {ident}\n"
            f"\tnas_type = other\n"
            f"\trequire_message_authenticator = no\n"
            f"}}\n\n"
        )
    return "".join(blocks)


async def render_from_db(db: AsyncSession) -> str:
    rows = (await db.execute(select(NasDevice).where(NasDevice.enabled.is_(True)))).scalars().all()
    return render([(r.name, str(r.ip), decrypt_secret(r.secret_encrypted)) for r in rows])


async def write_clients_file(db: AsyncSession, path: str | None = None) -> dict:
    """Atomic replace (write temp + rename) so radiusd never reads half a file."""
    target = Path(path or settings.radius_clients_path)
    content = await render_from_db(db)
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=".nas.", suffix=".tmp")
        with os.fdopen(fd, "w") as fh:
            fh.write(content)
        os.chmod(tmp, 0o640)
        os.replace(tmp, target)
        written = True
        error = None
    except OSError as exc:
        written, error = False, str(exc)
    return {
        "path": str(target),
        "written": written,
        "error": error,
        "sha256": hashlib.sha256(content.encode()).hexdigest(),
        "clients": content.count("\nclient ") + content.startswith("client "),
    }
